"""9. Integrate into private Git / Gerrit: commit per requirement, push to refs/for/<branch>,
HITL approval, optional Code-Review +2 and submit through the Gerrit REST API."""

from __future__ import annotations

import hashlib
import re
from pathlib import Path
from typing import Any
from urllib.parse import quote

from . import shell
from .config import Config
from .events import EventLog
from .guardrails import Guardrails
from .hitl import HITL
from .httpclient import basic_auth, request_json
from .state import Work

_CHANGE_URL = re.compile(r"https?://\S+/\+/\d+")


def make_change_id(seed: str) -> str:
    return "I" + hashlib.sha1(seed.encode(), usedforsecurity=False).hexdigest()


def commit_message(work: Work, change_id: str | None) -> str:
    req = work.requirement
    msg = f"{req.id}: {req.title}\n\nGenerated by the agentic SDLC framework.\n"
    if req.acceptance_criteria:
        msg += "\nAcceptance criteria:\n" + "\n".join(f"- {c}" for c in req.acceptance_criteria)
        msg += "\n"
    if change_id:
        msg += f"\nChange-Id: {change_id}\n"
    return msg


class GerritClient:
    def __init__(self, cfg: Config):
        self.url = (cfg.get("vcs.gerrit.url") or "").rstrip("/")
        user, token = cfg.secret("vcs.gerrit.user_env"), cfg.secret("vcs.gerrit.token_env")
        if not self.url or not user or not token:
            raise RuntimeError("vcs.gerrit.url and the Gerrit user/HTTP-password env vars must be set")
        self.headers = basic_auth(user, token)

    def _api(self, method: str, path: str, body: Any = None) -> Any:
        return request_json(method, f"{self.url}/a{path}", headers=self.headers, body=body)

    def get_change(self, change_id: str) -> dict:
        return self._api("GET", f"/changes/{quote(change_id, safe='')}?o=LABELS&o=CURRENT_REVISION")

    def review(self, change_id: str, labels: dict[str, int], message: str = "") -> dict:
        path = f"/changes/{quote(change_id, safe='')}/revisions/current/review"
        return self._api("POST", path, {"labels": labels, "message": message})

    def submit(self, change_id: str) -> dict:
        return self._api("POST", f"/changes/{quote(change_id, safe='')}/submit", {})

    def change_url(self, change: dict) -> str:
        return f"{self.url}/c/{change.get('project', '')}/+/{change.get('_number', '')}"


class VCS:
    def __init__(self, cfg: Config, events: EventLog, hitl: HITL, guardrails: Guardrails,
                 gerrit: GerritClient | None = None):
        self.cfg = cfg
        self.events = events
        self.hitl = hitl
        self.guardrails = guardrails
        self.mode = cfg.get("vcs.mode", "dry-run")
        self._gerrit = gerrit

    def _git(self, repo: Path, *args: str) -> shell.CommandResult:
        res = shell.run(["git", *args], cwd=repo)
        self.events.emit("gerrit", "git", cmd=" ".join(args), returncode=res.returncode)
        if not res.ok:
            raise RuntimeError(f"git {' '.join(args)} failed: {res.output}")
        return res

    def gerrit(self) -> GerritClient | None:
        if self._gerrit is None and self.cfg.get("vcs.gerrit.url"):
            self._gerrit = GerritClient(self.cfg)
        return self._gerrit

    def integrate(self, repo: Path, works: list[Work], run_id: str) -> dict[str, Any]:
        branch = self.cfg.get("vcs.branch", "main")
        topic = f"{self.cfg.get('vcs.branch_prefix', 'agentic/')}{run_id}"
        gerrit = self.mode == "gerrit"
        commits = [
            {"requirement": w.requirement.id, "files": w.files + w.test_files,
             "change_id": make_change_id(f"{run_id}:{w.requirement.id}") if gerrit else None}
            for w in works
        ]
        result: dict[str, Any] = {"mode": self.mode, "branch": branch, "topic": topic,
                                  "commits": commits, "ok": True}
        if not works:
            result["note"] = "no approved requirement implementations to integrate"
            return result
        if self.mode == "dry-run":
            result["push"] = f"git push {self.cfg.get('vcs.remote')} HEAD:refs/for/{branch}"
            return result
        if gerrit and self.guardrails.check_mcp("gerrit"):
            return {**result, "ok": False, "error": "gerrit integration is not approved"}
        try:
            self._git(repo, "checkout", "-B", topic)
            for c, w in zip(commits, works):
                self._git(repo, "add", "--", *c["files"])
                self._git(repo, "commit", "-m", commit_message(w, c["change_id"]))
                c["sha"] = self._git(repo, "rev-parse", "HEAD").stdout.strip()
            if gerrit:
                push = self._git(repo, "push", self.cfg.get("vcs.remote", "origin"),
                                 f"HEAD:refs/for/{branch}%topic={topic}")
                result["change_urls"] = _CHANGE_URL.findall(push.output)
                result["reviews"] = self._review(commits)
        except RuntimeError as exc:
            return {**result, "ok": False, "error": str(exc)}
        return result

    def _review(self, commits: list[dict]) -> list[dict]:
        client = self.gerrit()
        out = []
        for c in commits:
            entry: dict[str, Any] = {"change_id": c["change_id"], "status": "pushed"}
            if client:
                change = client.get_change(c["change_id"])
                entry.update(url=client.change_url(change), status=change.get("status", "NEW"))
            if not self.hitl.approve("merge", entry.get("url", c["change_id"])):
                entry["status"] = "awaiting human Code-Review +2"
            elif client and self.cfg.get("vcs.gerrit.auto_submit"):
                client.review(c["change_id"], {"Code-Review": 2}, "Approved via HITL gate")
                client.submit(c["change_id"])
                entry["status"] = "MERGED"
            else:
                entry["status"] = "approved; awaiting submit in Gerrit"
            out.append(entry)
        return out
